export type CardRow = {
  id: string;
  deck_id: string;
  front: string;
  back: string;
  position: number;
  created_at: string;
  updated_at: string;
  scheduling: {
    due_at: string;
    stability: number;
    difficulty: number;
    state: number;
    reps: number;
    lapses: number;
    last_reviewed_at: string | null;
  } | null;
};

const columnHelper = createColumnHelper<typeof features, CardRow>();

type CardStateConfig = {
  label: string;
  icon: LucideIcon;
  className: string;
};

function getCardStateConfig(state: number): CardStateConfig {
  switch (state) {
    case 0:
      return {
        label: "New",
        icon: Sparkles,
        className: "text-slate-600",
      };
    case 1:
      return {
        label: "Learning",
        icon: BookOpen,
        className: "text-blue-700",
      };
    case 2:
      return {
        label: "Review",
        icon: Brain,
        className: "text-green-700",
      };
    case 3:
      return {
        label: "Relearning",
        icon: RotateCcw,
        className: "text-orange-700",
      };
    default:
      return {
        label: "Unknown",
        icon: BookOpen,
        className: "text-muted-foreground",
      };
  }
}

